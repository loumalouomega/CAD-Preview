/** Minimal HTML text/attribute escaping shared by every host-built HTML page
 * (What's New, batch-export report, preparation report). */
export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
